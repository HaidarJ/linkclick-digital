"""Port the approved mockup (mockup/homepage.html) into the Astro site.

Re-runnable: it regenerates the files listed below from the mockup, so design changes made in the
mockup can be carried over. Files it writes:
  src/styles/site.css            the mockup CSS (fonts switched to the self-hosted families)
  src/components/SiteHeader.astro, SiteFooter.astro, StickyCta.astro
  src/components/home/Sections.astro   the homepage sections (hero to FAQ)
  src/data/home-schema.json      the homepage JSON-LD
  src/data/home-meta.json        the homepage <title> and meta description
Run from site/:  python3 scripts/port-mockup.py
"""
import json, pathlib, re

SITE = pathlib.Path(__file__).resolve().parent.parent
MOCK = SITE.parent / 'mockup' / 'homepage.html'
html = MOCK.read_text(encoding='utf-8')

LINKS = {
    '#contact': '/contact/', '#top': '/', '#insights': '/insights/', '#industries': '/industries/',
    '#about': '/about/', '#services': '/services/', '#web-design': '/services/web-design/',
    '#ugc': '/services/ugc-content/', '#digital-marketing': '/services/digital-marketing/',
    '#ai-automation': '/services/ai-automation/', '#privacy': '/privacy/', '#cookies': '/cookies/',
    '#complaints': '/complaint-policy/', '#addons-title': '/add-ons/', '#terms': '/terms/',
}


def relink(s):
    for a, b in LINKS.items():
        s = s.replace(f'href="{a}"', f'href="{b}"')
    left = sorted(set(re.findall(r'href="(#[^"]+)"', s)) - {'#main'})
    assert not left, left
    return s


def between(s, start, end):
    i = s.index(start)
    j = s.index(end, i)
    return s[i:j + len(end)]


def out(rel, text):
    p = SITE / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, encoding='utf-8')
    print('wrote', rel, len(text.encode()), 'bytes')


# ---- CSS
css = html.split('<style>', 1)[1].split('</style>', 1)[0].strip('\n')
for a, b in (('--font-sans: "Schibsted Grotesk",', '--font-sans: "Schibsted Grotesk Variable", "Schibsted Grotesk",'),
             ('--font-quote: "Newsreader",', '--font-quote: "Newsreader Variable", "Newsreader",')):
    assert css.count(a) == 1, a
    css = css.replace(a, b)
out('src/styles/site.css', '/* Generated from mockup/homepage.html by scripts/port-mockup.py. Edit the mockup\n'
    '   (or src/styles/pages.css for page templates), then re-run the script. */\n' + css + '\n')

# ---- title + meta description (so the homepage head always matches the mockup)
import html as _html
meta = {
    'title': _html.unescape(re.search(r'<title>(.*?)</title>', html).group(1)),
    'description': _html.unescape(re.search(r'<meta name="description" content="([^"]*)"', html).group(1)),
}
out('src/data/home-meta.json', json.dumps(meta, indent=2, ensure_ascii=False) + '\n')

# ---- JSON-LD
ld = html.split('<script type="application/ld+json">', 1)[1].split('</script>', 1)[0]
out('src/data/home-schema.json', json.dumps(json.loads(ld), indent=2, ensure_ascii=False) + '\n')

body = html.split('<body>', 1)[1]
assert '{' not in body.split('<script>', 1)[0], 'braces in markup would break Astro templates'

# ---- header + menu (+ the scroll thread)
header = relink(between(body, '<header class="site-header">', '</header>'))
i, j = body.index('<div class="menu" id="menu"'), body.index('<div class="thread"')
menu = relink(body[i:j].rstrip())
thread = between(body, '<div class="thread"', '</div>')
out('src/components/SiteHeader.astro', '---\n// Generated by scripts/port-mockup.py\n---\n' + header + '\n\n' + menu + '\n\n' + thread + '\n')

# ---- closing + footer (one dark sheet); the closing loses id="contact" because /contact/ is a page
dark = between(body, '<div class="on-dark sheet--top">', '</footer>\n  </div>')
dark = dark.replace('<section class="closing" id="contact"', '<section class="closing" data-closing')
out('src/components/SiteFooter.astro', '---\n// Generated by scripts/port-mockup.py\n---\n' + relink(dark) + '\n')

# ---- sticky mobile CTA
sticky = between(body, '<div class="sticky-cta" data-sticky>', '</div>')
out('src/components/StickyCta.astro', '---\n// Generated by scripts/port-mockup.py\n---\n' + relink(sticky) + '\n')

# ---- homepage sections: everything in <main> before the dark sheet
main = body.split('<main id="main">', 1)[1].split('<div class="on-dark sheet--top">', 1)[0].rstrip() + '\n'
a = '<section class="faq" id="insights"'
assert main.count(a) == 1
main = main.replace(a, '<section class="faq" id="faq"')
out('src/components/home/Sections.astro', '---\n// Generated by scripts/port-mockup.py\n---\n' + relink(main))

# ---- the four service figures, reused in the hero of each service hub
arts = [l.strip() for l in main.split('\n') if l.strip().startswith('<div class="pillar-art')]
assert len(arts) == 4, len(arts)
for name, art in zip(('Ugc', 'DigitalMarketing', 'WebDesign', 'AiAutomation'), arts):
    out(f'src/components/art/{name}.astro', '---\n// Generated by scripts/port-mockup.py\n---\n' + art + '\n')
